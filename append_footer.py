"""
Append footer comment to generated HCL files.

This script finds all .hcl files in a directory and appends a footer comment
from a template file. The footer serves as a label indicating the file was
generated by Terraform Policy Agent.

The template file (file_footer.hcl.template) must be in the same directory
as this script.

Usage:
    python3 append_footer.py <directory>

Arguments:
    directory: Directory containing HCL files (searches recursively)
"""

import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


def read_template(script_dir: Path) -> str:
    """Read the footer template from file in the same directory as this script."""
    template_path = script_dir / "file_footer.hcl.template"
    
    try:
        with open(template_path, 'r', encoding='utf-8') as f:
            return f.read()
    except FileNotFoundError:
        print(f"ERROR: Template file not found: {template_path}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: Failed to read template file: {e}", file=sys.stderr)
        sys.exit(1)


def parse_source_from_report(hcl_file_path: str) -> str:
    """
    Parse Input Source from report.md in the same directory as the HCL file.

    Supports two formats:
        ## Input Source
        ./data/input/sentinels/xxx.sentinel

        - **Input Source**: ./data/input/sentinels/xxx.sentinel
    """
    report_path = Path(hcl_file_path).parent / "report.md"
    if not report_path.exists():
        return "unknown"

    try:
        with open(report_path, 'r', encoding='utf-8') as f:
            lines = f.readlines()

        for i, line in enumerate(lines):
            # Format 1: - **Input Source**: <path>
            match = re.search(r'\*\*Input Source\*\*:\s*(\S+)', line)
            if match:
                return match.group(1)
            # Format 2: ## Input Source\n<path>
            if re.match(r'##\s+Input Source', line.strip()):
                if i + 1 < len(lines):
                    candidate = lines[i + 1].strip()
                    if candidate:
                        return candidate
            # Format 3: Input Source: <path>
            match = re.search(r'Input Source\s*:\s*(\S+)', line)
            if match:
                return match.group(1)
    except Exception:
        pass

    return "unknown"


def read_env_value(env_path: Path, key: str) -> str:
    """Read a single value from a .env file by key. Returns 'unknown' if not found."""
    if not env_path.exists():
        return "unknown"
    try:
        with open(env_path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line.startswith(f"{key}="):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    except Exception:
        pass
    return "unknown"


def build_footer(file_path: str, base_footer: str, time: str, provider: str, model: str) -> str:
    """
    Build a dynamic footer with generation timestamp, source file info, and LLM metadata.

    Args:
        file_path:   Path to the HCL file being processed.
        base_footer: Raw content from file_footer.hcl.template.
        time:        Pre-generated UTC timestamp string.
        provider:    AUTH_PROVIDER value from .env.
        model:       MODEL_NAME value from .env.

    Returns:
        Footer string with timestamp, source, and LLM info appended.
    """
    source = parse_source_from_report(file_path)
    return (
        f"{base_footer.rstrip()}\n"
        f"# Generated at: {time}\n"
        f"# Source: {source}\n"
        f"# LLM: {provider} / {model}\n"
    )


def find_hcl_files(directory: str) -> list:
    """Find all .hcl files in the directory recursively."""
    hcl_files = []
    try:
        for root, _, files in os.walk(directory):
            for file in files:
                if file.endswith('.hcl'):
                    hcl_files.append(os.path.join(root, file))
        return hcl_files
    except Exception as e:
        print(f"ERROR: Failed to search directory: {e}", file=sys.stderr)
        sys.exit(1)


def append_footer_to_file(file_path: str, footer: str) -> bool:
    """
    Append footer to a file if it doesn't already exist.
    
    Returns:
        True if footer was appended, False if it already exists
    """
    try:
        # Read the file content
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
        
        # Check if footer already exists (check first line of footer)
        footer_first_line = footer.strip().split('\n')[0]
        if footer_first_line in content:
            return False
        
        # Append footer (ensure there's a newline before the footer)
        if not content.endswith('\n'):
            content += '\n'
        content += '\n' + footer
        
        # Write back to file
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        
        return True
    except Exception as e:
        print(f"ERROR: Failed to process file {file_path}: {e}", file=sys.stderr)
        return False


def main():
    """Main function."""
    if len(sys.argv) != 2:
        print("Usage: python3 append_footer.py <directory>")
        print("")
        print("Arguments:")
        print("  directory: Directory containing HCL files (searches recursively)")
        print("")
        print("The template file (file_footer.hcl.template) must be in the same")
        print("directory as this script.")
        sys.exit(1)
    
    directory = sys.argv[1]
    
    # Validate directory exists
    if not os.path.isdir(directory):
        print(f"ERROR: Directory not found: {directory}", file=sys.stderr)
        sys.exit(1)
    
    # Get script directory
    script_dir = Path(__file__).parent
    
    # Find all HCL files
    hcl_files = find_hcl_files(directory)
    
    if not hcl_files:
        print(f"No .hcl files found in {directory}")
        return
    
    # Process each file
    appended_count = 0
    skipped_count = 0
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    env_path = script_dir / ".env"
    provider = read_env_value(env_path, "AUTH_PROVIDER")
    model = read_env_value(env_path, "MODEL_NAME")

    for file_path in hcl_files:
        footer = build_footer(file_path, read_template(script_dir), generated_at, provider, model)
        if append_footer_to_file(file_path, footer):
            print(f"✓ Appended footer to: {file_path}")
            appended_count += 1
        else:
            print(f"⊘ Skipped (footer exists): {file_path}")
            skipped_count += 1
    
    # Summary
    print("")
    print(f"Summary: {appended_count} file(s) updated, {skipped_count} file(s) skipped")


if __name__ == '__main__':
    main()
